def _compute_map_hash():
    items = sorted(SEMANTIC_MAP.items())
    joined = "".join(f"{k}:{v};" for k, v in items)
    return hashlib.sha256(joined.encode('utf-8')).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    hash_val = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (hash_val == _MAP_INTEGRITY_HASH)
    return {
        "status": "valid" if is_valid else "invalid",
        "entries": actual_count,
        "hash": hash_val,
        "is_valid": is_valid
    }

def normalize_term(term: str) -> str:
    t = term.strip().lower()
    t = re.sub(r"[\s\-_/]+", " ", t)
    t = t.replace(" per ft", " per foot")
    t = t.replace(" per ft.", " per foot")
    t = t.replace(" cost/ft", " cost per foot")
    t = t.replace(" cost/foot", " cost per foot")
    t = t.replace(" cost per ft", " cost per foot")
    t = t.replace(" d-exponent", " d exponent")
    t = t.replace(" dexponent", " d exponent")
    t = t.replace(" stick-slip", " stick slip")
    t = t.replace(" stickslip", " stick slip")
    t = t.replace(" mse", "mechanical specific energy")
    t = t.replace(" bha", "bottom hole assembly")
    t = t.replace(" mud", "drilling fluid")
    t = t.replace(" rpm", "revolutions per minute")
    t = t.replace(" wob", "weight on bit")
    t = t.replace(" rop", "rate of penetration")
    t = t.replace(" ilt", "invisible lost time")
    t = t.replace(" afe", "authorization for expenditure")
    t = t.replace(" pad development", "learning curve analysis pad development")
    t = re.sub(r"\s+", " ", t)
    t = t.strip()
    return SEMANTIC_MAP.get(t, t)

def get_related_terms(term: str) -> list:
    normalized = normalize_term(term)
    related = []
    for k, v in SEMANTIC_MAP.items():
        if v == normalized:
            related.append(k)
    return related


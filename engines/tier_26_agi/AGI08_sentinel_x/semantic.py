_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

_lock = threading.Lock()
_MAP_INTEGRITY_HASH = None

def _compute_map_hash() -> str:
    """
    Compute SHA256 hash of the SEMANTIC_MAP content sorted by keys and values.
    """
    hasher = hashlib.sha256()
    with _lock:
        for key in sorted(SEMANTIC_MAP.keys()):
            value = SEMANTIC_MAP[key]
            entry = f"{key}=>{value}\n"
            hasher.update(entry.encode('utf-8'))
    return hasher.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity() -> dict:
    """
    Verify the integrity of the SEMANTIC_MAP by comparing the current hash with the stored hash.
    Returns a dictionary with status, entries count, hash, and validity boolean.
    """
    current_hash = _compute_map_hash()
    is_valid = current_hash == _MAP_INTEGRITY_HASH and len(SEMANTIC_MAP) == _EXPECTED_ENTRY_COUNT
    return {
        "status": "valid" if is_valid else "invalid",
        "entries": len(SEMANTIC_MAP),
        "expected_entries": _EXPECTED_ENTRY_COUNT,
        "hash": current_hash,
        "expected_hash": _MAP_INTEGRITY_HASH,
        "is_valid": is_valid,
    }

def normalize_term(term: str) -> str:
    """
    Normalize a given term to its canonical form if present in SEMANTIC_MAP.
    Returns the normalized term or the original term lowercased if not found.
    """
    if not isinstance(term, str):
        raise TypeError("term must be a string")
    key = term.strip().lower()
    return SEMANTIC_MAP.get(key, key)

def get_related_terms(term: str) -> list[str]:
    """
    Get all terms that map to the same normalized term as the given term.
    Returns a list of related terms including the input term normalized.
    """
    if not isinstance(term, str):
        raise TypeError("term must be a string")
    normalized = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == normalized]
    if normalized not in related:
        related.append(normalized)
    return sorted(set(related))

def get_all_mappings() -> dict:
    """
    Return a copy of the entire SEMANTIC_MAP dictionary.
    """
    with _lock:
        return dict(SEMANTIC_MAP)
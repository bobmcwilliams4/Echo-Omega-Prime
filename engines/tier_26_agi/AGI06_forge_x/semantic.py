_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    joined = "\n".join(f"{k}:{v}" for k, v in items)
    hash_bytes = hashlib.sha256(joined.encode("utf-8")).hexdigest()
    return hash_bytes

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    expected_count = _EXPECTED_ENTRY_COUNT
    current_hash = _compute_map_hash()
    is_valid = (actual_count == expected_count) and (current_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "corrupt",
        "entries": actual_count,
        "expected_entries": expected_count,
        "hash": current_hash,
        "expected_hash": _MAP_INTEGRITY_HASH,
        "is_valid": is_valid,
    }

def _normalize_string(term):
    if not isinstance(term, str):
        return ""
    term = term.strip().lower()
    term = unicodedata.normalize("NFKC", term)
    term = " ".join(term.split())
    return term

def normalize_term(term):
    norm = _normalize_string(term)
    mapped = SEMANTIC_MAP.get(norm)
    if mapped:
        return mapped
    # Try to find close matches by removing underscores, etc.
    norm2 = norm.replace("_", " ")
    mapped2 = SEMANTIC_MAP.get(norm2)
    if mapped2:
        return mapped2
    return norm

def get_related_terms(term):
    norm = normalize_term(term)
    related = set()
    for k, v in SEMANTIC_MAP.items():
        if v == norm and k != norm:
            related.add(k)
    return sorted(related)

def get_all_mappings():
    return dict(SEMANTIC_MAP)
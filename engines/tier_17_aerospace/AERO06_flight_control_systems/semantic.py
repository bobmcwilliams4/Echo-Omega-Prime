_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash():
    items = sorted((k.lower().strip(), v.lower().strip()) for k, v in SEMANTIC_MAP.items())
    concat = ''.join(f"{k}:{v};" for k, v in items)
    return hashlib.sha256(concat.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    hash_now = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (hash_now == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "invalid",
        "entries": actual_count,
        "hash": hash_now,
        "is_valid": is_valid,
        "expected_entries": _EXPECTED_ENTRY_COUNT,
        "expected_hash": _MAP_INTEGRITY_HASH,
    }

def _normalize_key(term):
    if not isinstance(term, str):
        return ""
    t = term.lower()
    t = t.replace("-", " ")
    t = re.sub(r"\s+", " ", t)
    t = t.strip()
    return t

def normalize_term(term: str) -> str:
    key = _normalize_key(term)
    return SEMANTIC_MAP.get(key, key)

def get_related_terms(term: str) -> list:
    normalized = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == normalized]
    return sorted(set(related))


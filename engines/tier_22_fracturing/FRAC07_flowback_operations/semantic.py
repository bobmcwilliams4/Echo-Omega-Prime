_EXPECTED_ENTRY_COUNT = 269

def _compute_map_hash() -> str:
    items = sorted((k, SEMANTIC_MAP[k]) for k in SEMANTIC_MAP)
    hash_input = "".join(f"{k}:{v};" for k, v in items)
    return hashlib.sha256(hash_input.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity() -> dict:
    actual_count = len(SEMANTIC_MAP)
    expected_count = _EXPECTED_ENTRY_COUNT
    actual_hash = _compute_map_hash()
    is_valid = (actual_count == expected_count) and (actual_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": actual_hash,
        "is_valid": is_valid,
    }

def _normalize_string(term: str) -> str:
    term = term.lower()
    term = re.sub(r"[^a-z0-9\s\-_/]", "", term)
    term = re.sub(r"\s+", " ", term)
    term = term.strip()
    return term

def normalize_term(term: str) -> str:
    norm = _normalize_string(term)
    return SEMANTIC_MAP.get(norm, norm)

def get_related_terms(term: str) -> List[str]:
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return sorted(set(related))

def get_all_mappings() -> Dict[str, str]:
    return dict(SEMANTIC_MAP)
def normalize_term(term: str) -> str:
    t = term.strip().lower()
    t = re.sub(r"\s+", " ", t)
    if t in SEMANTIC_MAP:
        return SEMANTIC_MAP[t]
    # Try removing hyphens, underscores, extra spaces
    t2 = re.sub(r"[-_]", " ", t)
    t2 = re.sub(r"\s+", " ", t2)
    if t2 in SEMANTIC_MAP:
        return SEMANTIC_MAP[t2]
    # Try removing plural 's'
    if t.endswith("s") and t[:-1] in SEMANTIC_MAP:
        return SEMANTIC_MAP[t[:-1]]
    # Try removing 'ing', 'ed'
    for suffix in ["ing", "ed"]:
        if t.endswith(suffix) and t[:-len(suffix)] in SEMANTIC_MAP:
            return SEMANTIC_MAP[t[:-len(suffix)]]
    # Try removing 'es'
    if t.endswith("es") and t[:-2] in SEMANTIC_MAP:
        return SEMANTIC_MAP[t[:-2]]
    return t

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    related = []
    for k, v in SEMANTIC_MAP.items():
        if v == norm and k != term:
            related.append(k)
    return related


_EXPECTED_ENTRY_COUNT = 347

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    joined = "\n".join(f"{k}=>{v}" for k, v in items)
    return hashlib.sha256(joined.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    expected = _EXPECTED_ENTRY_COUNT
    hash_val = _compute_map_hash()
    is_valid = (actual_count == expected) and (hash_val == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": hash_val,
        "is_valid": is_valid,
        "expected_count": expected,
        "expected_hash": _MAP_INTEGRITY_HASH,
    }

def _normalize(s):
    s = s.lower()
    s = re.sub(r"[\u2018\u2019\u201c\u201d]", "'", s)
    s = re.sub(r"[^a-z0-9\- ]+", "", s)
    s = re.sub(r"\s+", " ", s)
    s = s.strip()
    return s

def normalize_term(term):
    norm = _normalize(term)
    return SEMANTIC_MAP.get(norm, norm)

def get_related_terms(term):
    norm = normalize_term(term)
    return [k for k, v in SEMANTIC_MAP.items() if v == norm]

def get_all_mappings():
    return dict(SEMANTIC_MAP)
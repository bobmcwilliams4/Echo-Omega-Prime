_EXPECTED_ENTRY_COUNT = 243

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    hash_input = "".join(f"{k}:{v};" for k, v in items)
    hash_bytes = hash_input.encode("utf-8")
    return hashlib.sha256(hash_bytes).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    entries = len(SEMANTIC_MAP)
    hash_val = _compute_map_hash()
    is_valid = (entries == _EXPECTED_ENTRY_COUNT) and (hash_val == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": entries,
        "hash": hash_val,
        "is_valid": is_valid,
        "expected_entries": _EXPECTED_ENTRY_COUNT,
        "expected_hash": _MAP_INTEGRITY_HASH,
    }

def _normalize_string(s):
    s = s.strip().lower()
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = " ".join(s.split())
    return s

def normalize_term(term):
    t = _normalize_string(term)
    return SEMANTIC_MAP.get(t, t)

def get_related_terms(term):
    norm = normalize_term(term)
    return [k for k, v in SEMANTIC_MAP.items() if v == norm]

def get_all_mappings():
    return dict(SEMANTIC_MAP)
SEMANTIC_MAP.update(_EXTRA_ENTRIES)

_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _normalize_key(key):
    key = unicodedata.normalize('NFKC', key)
    key = key.lower()
    key = key.strip()
    key = key.replace("_", " ")
    key = " ".join(key.split())
    return key

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    m = hashlib.sha256()
    for k, v in items:
        m.update(k.encode("utf-8"))
        m.update(b"->")
        m.update(v.encode("utf-8"))
        m.update(b"\n")
    m.update(str(_EXPECTED_ENTRY_COUNT).encode("utf-8"))
    m.update(SEMANTIC_MAP_VERSION.encode("utf-8"))
    m.update(SEMANTIC_MAP_ENGINE.encode("utf-8"))
    m.update(SEMANTIC_MAP_AUTHOR.encode("utf-8"))
    return m.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    actual_hash = _compute_map_hash()
    is_valid = (
        actual_count == _EXPECTED_ENTRY_COUNT and
        actual_hash == _MAP_INTEGRITY_HASH
    )
    return {
        "status": "ok" if is_valid else "fail",
        "entries": actual_count,
        "hash": actual_hash,
        "expected_entries": _EXPECTED_ENTRY_COUNT,
        "expected_hash": _MAP_INTEGRITY_HASH,
        "is_valid": is_valid,
    }

def normalize_term(term):
    key = _normalize_key(term)
    return SEMANTIC_MAP.get(key, key)

def get_related_terms(term):
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return sorted(set(related))

def get_all_mappings():
    return dict(SEMANTIC_MAP)
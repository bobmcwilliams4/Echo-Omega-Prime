def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    m = hashlib.sha256()
    for k, v in items:
        m.update(k.encode("utf-8"))
        m.update(v.encode("utf-8"))
    return m.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    hash_val = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (hash_val == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": hash_val,
        "is_valid": is_valid,
    }

def normalize_term(term: str) -> str:
    if not isinstance(term, str):
        return ""
    t = term.strip().lower()
    t = re.sub(r"[_\-\s]+", " ", t)
    t = t.strip()
    # Try direct
    if t in SEMANTIC_MAP:
        return SEMANTIC_MAP[t]
    # Try with underscores
    t_ = t.replace(" ", "_")
    if t_ in SEMANTIC_MAP:
        return SEMANTIC_MAP[t_]
    # Try with dashes
    t_dash = t.replace(" ", "-")
    if t_dash in SEMANTIC_MAP:
        return SEMANTIC_MAP[t_dash]
    # Try removing spaces
    t_nospace = t.replace(" ", "")
    if t_nospace in SEMANTIC_MAP:
        return SEMANTIC_MAP[t_nospace]
    # Try removing dashes/underscores
    t_nodash = t.replace("-", "")
    t_nounder = t.replace("_", "")
    if t_nodash in SEMANTIC_MAP:
        return SEMANTIC_MAP[t_nodash]
    if t_nounder in SEMANTIC_MAP:
        return SEMANTIC_MAP[t_nounder]
    # Try removing all non-alphanum
    t_alphanum = re.sub(r"[^a-z0-9]", "", t)
    if t_alphanum in SEMANTIC_MAP:
        return SEMANTIC_MAP[t_alphanum]
    return ""

def get_related_terms(term: str):
    norm = normalize_term(term)
    if not norm:
        return []
    return sorted(_RELATED_TERMS_INDEX.get(norm, []))


def _normalize_key(key):
    key = key.lower()
    key = unicodedata.normalize('NFKC', key)
    key = key.replace("-", " ").replace("_", " ")
    key = " ".join(key.split())
    return key

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    hash_input = "".join(f"{k}:{v};" for k, v in items)
    h = hashlib.sha256(hash_input.encode("utf-8")).hexdigest()
    return h

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    status = "ok" if actual_count == _EXPECTED_ENTRY_COUNT else "count_mismatch"
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT)
    return {
        "status": status,
        "entries": actual_count,
        "expected": _EXPECTED_ENTRY_COUNT,
        "hash": _MAP_INTEGRITY_HASH,
        "is_valid": is_valid,
        "version": SEMANTIC_MAP_VERSION,
        "engine": SEMANTIC_MAP_ENGINE,
    }

def normalize_term(term):
    key = _normalize_key(term)
    return SEMANTIC_MAP.get(key, key)

def get_related_terms(term):
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]

_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash() -> str:
    items = sorted(SEMANTIC_MAP.items())
    joined = "".join(f"{k}:{v};" for k, v in items)
    meta = f"{SEMANTIC_MAP_VERSION}:{SEMANTIC_MAP_AUTHOR}:{SEMANTIC_MAP_ENGINE}:{_EXPECTED_ENTRY_COUNT}"
    full = meta + joined
    return hashlib.sha256(full.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity() -> Dict[str, object]:
    actual_count = len(SEMANTIC_MAP)
    hash_val = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (hash_val == _MAP_INTEGRITY_HASH)
    return {
        "status": "valid" if is_valid else "invalid",
        "entries": actual_count,
        "hash": hash_val,
        "is_valid": is_valid,
    }

def _normalize_string(term: str) -> str:
    term = term.lower()
    term = term.strip()
    term = re.sub(r"\s+", " ", term)
    term = re.sub(r"[\-_/]", " ", term)
    term = re.sub(r"\s+", " ", term)
    return term

def normalize_term(term: str) -> str:
    norm = _normalize_string(term)
    mapped = SEMANTIC_MAP.get(norm)
    if mapped:
        return mapped
    # Try direct mapping for some common misspellings or variants
    norm2 = norm.replace("sulphide", "sulfide").replace("dewaard", "de waard")
    mapped2 = SEMANTIC_MAP.get(norm2)
    if mapped2:
        return mapped2
    return norm

def get_related_terms(term: str) -> List[str]:
    norm = normalize_term(term)
    related = []
    for k, v in SEMANTIC_MAP.items():
        if v == norm and k != norm:
            related.append(k)
    return related

def get_all_mappings() -> Dict[str, str]:
    return dict(SEMANTIC_MAP)
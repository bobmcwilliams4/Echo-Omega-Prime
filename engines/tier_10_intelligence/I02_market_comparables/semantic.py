_EXPECTED_ENTRY_COUNT = 242

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    m = hashlib.sha256()
    for k, v in items:
        m.update(k.encode("utf-8"))
        m.update(b"=")
        m.update(v.encode("utf-8"))
        m.update(b";")
    return m.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    expected_count = _EXPECTED_ENTRY_COUNT
    hash_val = _compute_map_hash()
    is_valid = (actual_count == expected_count) and (hash_val == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": hash_val,
        "is_valid": is_valid,
    }

def _normalize_unicode(term):
    return unicodedata.normalize("NFKD", term).encode("ascii", "ignore").decode("ascii")

def normalize_term(term: str) -> str:
    if not isinstance(term, str):
        return ""
    t = term.strip().lower()
    t = _normalize_unicode(t)
    return SEMANTIC_MAP.get(t, t)

def get_related_terms(term: str) -> list:
    if not isinstance(term, str):
        return []
    t = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == t]
    return sorted(set(related))

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
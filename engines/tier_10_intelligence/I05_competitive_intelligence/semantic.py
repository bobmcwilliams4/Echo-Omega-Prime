_EXPECTED_ENTRY_COUNT = 400

def _compute_map_hash():
    items = sorted((k.lower(), v.lower()) for k, v in SEMANTIC_MAP.items())
    map_bytes = repr(items).encode("utf-8")
    return hashlib.sha256(map_bytes).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    is_valid = actual_count >= _EXPECTED_ENTRY_COUNT and _MAP_INTEGRITY_HASH == _compute_map_hash()
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": _MAP_INTEGRITY_HASH,
        "is_valid": is_valid,
    }

def _normalize_key(term):
    if not isinstance(term, str):
        return ""
    return re.sub(r"\s+", " ", term.strip().lower())

def normalize_term(term):
    k = _normalize_key(term)
    if k in SEMANTIC_MAP:
        return SEMANTIC_MAP[k]
    # Try original case
    if term in SEMANTIC_MAP:
        return SEMANTIC_MAP[term]
    # Try title case
    tcase = term.title()
    if tcase in SEMANTIC_MAP:
        return SEMANTIC_MAP[tcase]
    # Try removing hyphens
    kh = k.replace("-", " ")
    if kh in SEMANTIC_MAP:
        return SEMANTIC_MAP[kh]
    # Try removing plural 's'
    if k.endswith("s") and k[:-1] in SEMANTIC_MAP:
        return SEMANTIC_MAP[k[:-1]]
    return k

def get_related_terms(term):
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return sorted(set(related))

def get_all_mappings():
    return dict(SEMANTIC_MAP)
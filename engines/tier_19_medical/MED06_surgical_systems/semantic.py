def _compute_map_hash() -> str:
    items = sorted(SEMANTIC_MAP.items())
    map_str = "".join(f"{k}:{v};" for k, v in items)
    meta_str = (
        f"version:{SEMANTIC_MAP_VERSION};"
        f"author:{SEMANTIC_MAP_AUTHOR};"
        f"engine:{SEMANTIC_MAP_ENGINE};"
        f"count:{_EXPECTED_ENTRY_COUNT};"
    )
    full_str = meta_str + map_str
    return hashlib.sha256(full_str.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity() -> dict:
    actual_count = len(SEMANTIC_MAP)
    hash_val = _compute_map_hash()
    is_valid = (
        actual_count == _EXPECTED_ENTRY_COUNT
        and hash_val == _MAP_INTEGRITY_HASH
    )
    return {
        "status": "valid" if is_valid else "invalid",
        "entries": actual_count,
        "hash": hash_val,
        "is_valid": is_valid,
    }

def normalize_term(term: str) -> str:
    t = term.strip().lower()
    t = re.sub(r"\s+", " ", t)
    return SEMANTIC_MAP.get(t, t)

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return related

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
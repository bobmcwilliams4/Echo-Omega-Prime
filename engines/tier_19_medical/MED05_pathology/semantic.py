_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash():
    items = sorted(SEMANTIC_MAP.items())
    concat = "".join(f"{k}:{v};" for k, v in items)
    concat += f"version:{SEMANTIC_MAP_VERSION};author:{SEMANTIC_MAP_AUTHOR};engine:{SEMANTIC_MAP_ENGINE};count:{_EXPECTED_ENTRY_COUNT};"
    return hashlib.sha256(concat.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    current_count = len(SEMANTIC_MAP)
    current_hash = _compute_map_hash()
    is_valid = (current_count == _EXPECTED_ENTRY_COUNT) and (current_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": current_count,
        "hash": current_hash,
        "is_valid": is_valid,
        "expected_entries": _EXPECTED_ENTRY_COUNT,
        "expected_hash": _MAP_INTEGRITY_HASH,
        "version": SEMANTIC_MAP_VERSION,
        "author": SEMANTIC_MAP_AUTHOR,
        "engine": SEMANTIC_MAP_ENGINE,
    }

def normalize_term(term: str) -> str:
    t = term.strip().lower()
    t = re.sub(r"[\s\-_.]+", " ", t)
    t = t.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    t = t.replace("’s", "s")
    t = t.strip()
    if t in SEMANTIC_MAP:
        return SEMANTIC_MAP[t]
    t2 = t.replace(".", "")
    if t2 in SEMANTIC_MAP:
        return SEMANTIC_MAP[t2]
    t3 = t.replace(" ", "")
    if t3 in SEMANTIC_MAP:
        return SEMANTIC_MAP[t3]
    return t

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return sorted(set(related))

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
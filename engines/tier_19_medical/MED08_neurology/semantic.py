def _compute_map_hash():
    items = sorted(SEMANTIC_MAP.items())
    hash_input = "".join(f"{k}:{v};" for k, v in items)
    return hashlib.sha256(hash_input.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    hash_val = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (hash_val == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": hash_val,
        "is_valid": is_valid,
        "expected_count": _EXPECTED_ENTRY_COUNT,
        "expected_hash": _MAP_INTEGRITY_HASH,
    }

def normalize_term(term: str) -> str:
    t = term.strip().lower()
    t = re.sub(r"['’]", "", t)
    t = re.sub(r"\s+", " ", t)
    if t in SEMANTIC_MAP:
        return SEMANTIC_MAP[t]
    # Try removing plural
    if t.endswith("s") and t[:-1] in SEMANTIC_MAP:
        return SEMANTIC_MAP[t[:-1]]
    # Try removing hyphens
    t2 = t.replace("-", " ")
    if t2 in SEMANTIC_MAP:
        return SEMANTIC_MAP[t2]
    # Try removing spaces
    t3 = t.replace(" ", "")
    if t3 in SEMANTIC_MAP:
        return SEMANTIC_MAP[t3]
    return t

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    return sorted(set(_REVERSE_MAP.get(norm, [])))

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
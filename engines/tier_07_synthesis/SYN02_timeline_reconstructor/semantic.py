_EXPECTED_ENTRY_COUNT = 400

def _compute_map_hash():
    items = sorted(SEMANTIC_MAP.items())
    hasher = hashlib.sha256()
    for k, v in items:
        line = f"{k}=>{v}\n"
        hasher.update(line.encode("utf-8"))
    return hasher.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    expected = _EXPECTED_ENTRY_COUNT
    hash_now = _compute_map_hash()
    is_valid = (actual_count == expected) and (hash_now == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "expected": expected,
        "hash": hash_now,
        "expected_hash": _MAP_INTEGRITY_HASH,
        "is_valid": is_valid,
    }

def _normalize_input(term):
    if not isinstance(term, str):
        return ""
    term = term.strip().lower()
    term = unicodedata.normalize("NFKC", term)
    term = " ".join(term.split())
    return term

def normalize_term(term: str) -> str:
    norm = _normalize_input(term)
    return SEMANTIC_MAP.get(norm, norm)

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return related

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
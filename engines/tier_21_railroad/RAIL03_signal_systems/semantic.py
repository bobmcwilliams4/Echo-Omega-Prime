_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash() -> str:
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    hasher = hashlib.sha256()
    for k, v in items:
        hasher.update(k.encode("utf-8"))
        hasher.update(b"=")
        hasher.update(v.encode("utf-8"))
        hasher.update(b";")
    return hasher.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity() -> dict:
    actual_count = len(SEMANTIC_MAP)
    current_hash = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (current_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": current_hash,
        "is_valid": is_valid,
        "expected_entries": _EXPECTED_ENTRY_COUNT,
        "expected_hash": _MAP_INTEGRITY_HASH,
    }

def _normalize(s: str) -> str:
    s = s.lower()
    s = re.sub(r"[^a-z0-9\- ]+", "", s)
    s = re.sub(r"\s+", " ", s)
    return s.strip()

def normalize_term(term: str) -> str:
    norm = _normalize(term)
    return SEMANTIC_MAP.get(norm, norm)

def get_related_terms(term: str) -> List[str]:
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return sorted(set(related))

def get_all_mappings() -> Dict[str, str]:
    return dict(SEMANTIC_MAP)
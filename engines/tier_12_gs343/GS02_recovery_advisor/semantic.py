_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash():
    items = sorted(SEMANTIC_MAP.items())
    data = "".join(f"{k}:{v};" for k, v in items)
    meta = f"{SEMANTIC_MAP_VERSION}|{SEMANTIC_MAP_AUTHOR}|{SEMANTIC_MAP_ENGINE}|{_EXPECTED_ENTRY_COUNT}"
    full_data = meta + "|" + data
    return hashlib.sha256(full_data.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    actual_hash = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (actual_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": actual_hash,
        "is_valid": is_valid,
    }

def _normalize_string(term):
    if not isinstance(term, str):
        return ""
    t = term.lower()
    t = t.strip()
    t = re.sub(r"[_\-]+", " ", t)
    t = re.sub(r"\s+", " ", t)
    t = t.replace("’", "'")
    t = t.replace("`", "'")
    t = t.replace('"', "")
    t = t.replace(".", "")
    t = t.replace(",", "")
    t = t.replace("(", "")
    t = t.replace(")", "")
    t = t.replace("[", "")
    t = t.replace("]", "")
    t = t.replace("{", "")
    t = t.replace("}", "")
    t = t.replace(":", "")
    t = t.replace(";", "")
    t = t.replace("!", "")
    t = t.replace("?", "")
    t = t.replace("/", " ")
    t = t.replace("\\", " ")
    t = t.strip()
    return t

def normalize_term(term):
    norm = _normalize_string(term)
    return SEMANTIC_MAP.get(norm, norm)

def get_related_terms(term):
    norm = normalize_term(term)
    related = []
    for k, v in SEMANTIC_MAP.items():
        if v == norm and _normalize_string(term) != k:
            related.append(k)
    return related

def get_all_mappings():
    return dict(SEMANTIC_MAP)
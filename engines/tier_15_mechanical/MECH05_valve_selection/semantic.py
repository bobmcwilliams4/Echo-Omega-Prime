def _normalize(s):
    s = s.lower()
    s = re.sub(r"[^a-z0-9&\.\-\s]", "", s)
    s = re.sub(r"\s+", " ", s)
    return s.strip()

def normalize_term(term):
    t = _normalize(term)
    # resolve recursively to the canonical form
    visited = set()
    while t in SEMANTIC_MAP and t not in visited:
        visited.add(t)
        t = SEMANTIC_MAP[t]
        t = _normalize(t)
    return t

def get_related_terms(term):
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if normalize_term(v) == norm]

    t = term.strip().lower()
    t = re.sub(r"\s+", " ", t)
    t = re.sub(r"[^a-z0-9 \-\_]", "", t)
    t = t.replace("-", " ")
    t = re.sub(r"\s+", " ", t)
    t = t.strip()
    return SEMANTIC_MAP.get(t, t)


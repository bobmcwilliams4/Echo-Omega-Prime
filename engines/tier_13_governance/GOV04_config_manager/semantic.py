_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash() -> str:
    items = sorted(SEMANTIC_MAP.items())
    hasher = hashlib.sha256()
    for k, v in items:
        hasher.update(k.encode("utf-8"))
        hasher.update(b"=")
        hasher.update(v.encode("utf-8"))
        hasher.update(b";")
    hasher.update(str(_EXPECTED_ENTRY_COUNT).encode("utf-8"))
    hasher.update(SEMANTIC_MAP_VERSION.encode("utf-8"))
    hasher.update(SEMANTIC_MAP_ENGINE.encode("utf-8"))
    return hasher.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity() -> dict:
    current_hash = _compute_map_hash()
    is_valid = current_hash == _MAP_INTEGRITY_HASH and len(SEMANTIC_MAP) == _EXPECTED_ENTRY_COUNT
    return {
        "status": "valid" if is_valid else "invalid",
        "entries": len(SEMANTIC_MAP),
        "hash": current_hash,
        "is_valid": is_valid,
    }

def _normalize_key(term: str) -> str:
    term = term.strip().lower()
    term = re.sub(r"[\s\-]+", "_", term)
    term = re.sub(r"[^a-z0-9_]", "", term)
    return term

def normalize_term(term: str) -> str:
    key = _normalize_key(term)
    return SEMANTIC_MAP.get(key, key)

def get_related_terms(term: str) -> List[str]:
    normalized = normalize_term(term)
    return [k for k, v in SEMANTIC_MAP.items() if v == normalized]

def get_all_mappings() -> Dict[str, str]:
    return dict(SEMANTIC_MAP)
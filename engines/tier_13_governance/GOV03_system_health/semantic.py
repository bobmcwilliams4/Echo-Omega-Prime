# Build reverse mapping for related terms
_RELATED_TERMS = {}
for k, v in SEMANTIC_MAP.items():
    _RELATED_TERMS.setdefault(v, set()).add(k)
for v in _RELATED_TERMS:
    _RELATED_TERMS[v] = list(sorted(_RELATED_TERMS[v]))

def _compute_map_hash():
    items = sorted(SEMANTIC_MAP.items())
    m = hashlib.sha256()
    for k, v in items:
        m.update(k.encode("utf-8"))
        m.update(b"=")
        m.update(v.encode("utf-8"))
        m.update(b";")
    return m.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

_integrity_lock = threading.Lock()

def verify_integrity():
    with _integrity_lock:
        actual_count = len(SEMANTIC_MAP)
        actual_hash = _compute_map_hash()
        is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (actual_hash == _MAP_INTEGRITY_HASH)
        return {
            "status": "ok" if is_valid else "invalid",
            "entries": actual_count,
            "hash": actual_hash,
            "is_valid": is_valid
        }

def normalize_term(term: str) -> str:
    if not isinstance(term, str):
        return ""
    t = term.strip().lower()
    return SEMANTIC_MAP.get(t, "")

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    if not norm:
        return []
    return [t for t in _RELATED_TERMS.get(norm, []) if t != term.strip().lower()]

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
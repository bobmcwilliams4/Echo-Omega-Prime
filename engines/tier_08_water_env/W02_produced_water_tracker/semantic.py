_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash():
    items = sorted((k.strip().lower(), v.strip().lower()) for k, v in SEMANTIC_MAP.items())
    joined = "|".join(f"{k}:{v}" for k, v in items)
    return hashlib.sha256(joined.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    actual_hash = _compute_map_hash()
    is_valid = (actual_count == _EXPECTED_ENTRY_COUNT) and (actual_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "expected_entries": _EXPECTED_ENTRY_COUNT,
        "hash": actual_hash,
        "expected_hash": _MAP_INTEGRITY_HASH,
        "is_valid": is_valid,
    }

def _normalize_string(s):
    s = s.lower()
    s = re.sub(r"[\.\-_/]", " ", s)
    s = re.sub(r"\s+", " ", s)
    s = s.strip()
    return s

def normalize_term(term: str) -> str:
    term_norm = _normalize_string(term)
    if term in SEMANTIC_MAP:
        return SEMANTIC_MAP[term]
    if term_norm in SEMANTIC_MAP:
        return SEMANTIC_MAP[term_norm]
    # Try more aggressive normalization
    term_norm2 = re.sub(r"[^a-z0-9 ]", "", term_norm)
    if term_norm2 in SEMANTIC_MAP:
        return SEMANTIC_MAP[term_norm2]
    # Try removing plural 's'
    if term_norm2.endswith("s") and term_norm2[:-1] in SEMANTIC_MAP:
        return SEMANTIC_MAP[term_norm2[:-1]]
    return term_norm

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return sorted(set(related))

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
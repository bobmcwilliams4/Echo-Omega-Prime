_EXPECTED_ENTRY_COUNT = len(SEMANTIC_MAP)

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    map_bytes = repr(items).encode("utf-8")
    return hashlib.sha256(map_bytes).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    expected_count = _EXPECTED_ENTRY_COUNT
    hash_now = _compute_map_hash()
    is_valid = (actual_count == expected_count) and (hash_now == _MAP_INTEGRITY_HASH)
    return {
        "status": "OK" if is_valid else "FAIL",
        "entries": actual_count,
        "hash": hash_now,
        "is_valid": is_valid
    }

def _normalize_key(term):
    if not isinstance(term, str):
        return ""
    term = term.lower()
    term = term.strip()
    term = re.sub(r"\s+", " ", term)
    return term

def normalize_term(term: str) -> str:
    key = _normalize_key(term)
    return SEMANTIC_MAP.get(key, key)

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    related = [k for k, v in SEMANTIC_MAP.items() if v == norm]
    return sorted(set(related))

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
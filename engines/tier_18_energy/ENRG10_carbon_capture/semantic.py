_EXPECTED_ENTRY_COUNT = 250

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    m = hashlib.sha256()
    for k, v in items:
        m.update(k.encode("utf-8"))
        m.update(b"::")
        m.update(v.encode("utf-8"))
        m.update(b"\n")
    return m.hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    expected_count = _EXPECTED_ENTRY_COUNT
    current_hash = _compute_map_hash()
    is_valid = (actual_count == expected_count) and (current_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": current_hash,
        "is_valid": is_valid,
        "expected_entries": expected_count,
        "expected_hash": _MAP_INTEGRITY_HASH,
    }

def _normalize_string(s):
    s = s.lower()
    s = re.sub(r"[^a-z0-9\s\-]", "", s)
    s = re.sub(r"\s+", " ", s)
    s = s.strip()
    return s

def normalize_term(term: str) -> str:
    key = _normalize_string(term)
    return SEMANTIC_MAP.get(key, key)

def get_related_terms(term: str) -> list:
    norm = normalize_term(term)
    return [k for k, v in SEMANTIC_MAP.items() if v == norm]

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)
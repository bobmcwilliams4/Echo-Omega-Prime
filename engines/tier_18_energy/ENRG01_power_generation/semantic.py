_EXPECTED_ENTRY_COUNT = 230

def _compute_map_hash():
    items = sorted((k, v) for k, v in SEMANTIC_MAP.items())
    concat = "".join(f"{k}:{v};" for k, v in items)
    concat += f"version:{SEMANTIC_MAP_VERSION};author:{SEMANTIC_MAP_AUTHOR};engine:{SEMANTIC_MAP_ENGINE};count:{_EXPECTED_ENTRY_COUNT};"
    return hashlib.sha256(concat.encode("utf-8")).hexdigest()

_MAP_INTEGRITY_HASH = _compute_map_hash()

def verify_integrity():
    actual_count = len(SEMANTIC_MAP)
    expected = _EXPECTED_ENTRY_COUNT
    actual_hash = _compute_map_hash()
    is_valid = (actual_count == expected) and (actual_hash == _MAP_INTEGRITY_HASH)
    return {
        "status": "ok" if is_valid else "error",
        "entries": actual_count,
        "hash": actual_hash,
        "is_valid": is_valid
    }

def normalize_term(term: str) -> str:
    if not isinstance(term, str):
        return ""
    t = term.lower().strip()
    t = re.sub(r"[\s\-]+", " ", t)
    t = t.replace("&", "and")
    t = t.replace("’", "'")
    t = t.replace("‘", "'")
    t = t.replace("“", '"').replace("”", '"')
    t = t.replace("–", "-").replace("—", "-")
    t = re.sub(r"\s+", " ", t)
    t = t.strip()
    return SEMANTIC_MAP.get(t, t)

def get_related_terms(term: str) -> list:
    if not isinstance(term, str):
        return []
    norm = normalize_term(term)
    return [k for k, v in SEMANTIC_MAP.items() if v == norm]

def get_all_mappings() -> dict:
    return dict(SEMANTIC_MAP)